function isLocale(value: string | null): value is Locale {
	return value !== null && LOCALES.some((locale) => locale === value);
}

function getInitialLocale(): Locale {
	try {
		const stored = window.localStorage.getItem(STORAGE_KEY);
		if (isLocale(stored)) return stored;
	} catch {
		console.warn('Unable to read the saved language preference.');
	}

	const browserLanguages = navigator.languages.length
		? navigator.languages
		: [navigator.language];
	for (const language of browserLanguages) {
		const languageCode = language.toLowerCase().split('-')[0];
		if (isLocale(languageCode)) return languageCode;
	}
	return 'en';
}

export function LocalizationProvider({ children }: { children: ReactNode }) {
	const [locale, setLocaleState] = useState<Locale>(getInitialLocale);
	const direction = locale === 'ar' ? 'rtl' : 'ltr';

	useEffect(() => {
		document.documentElement.lang = locale;
		document.documentElement.dir = direction;
		try {
			window.localStorage.setItem(STORAGE_KEY, locale);
		} catch {
			console.warn('Unable to save the language preference.');
		}
	}, [direction, locale]);

	const value = useMemo<LocalizationContextValue>(
		() => ({
			locale,
			direction,
			setLocale: setLocaleState,
			t: (key) => messages[locale][key],
		}),
		[direction, locale],
	);

	return (
		<LocalizationContext.Provider value={value}>
			{children}
		</LocalizationContext.Provider>
	);
}
